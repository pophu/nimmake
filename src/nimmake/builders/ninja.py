    def __build_ninja_content(self) -> str:
        # 1. 文件头
        self._build_ninja_header()

        # 2. 工具链变量
        self._build_ninja_tool_chain()

        # 3. 编译/链接标志变量
        self._build_ninja_compile_flags()

        # 3.1 编译/链接标志变量 party
        self._build_ninja_party_defines_include()

        # 4. 编译规则
        self._build_ninja_compile_rules()

        # 4.1 party 编译规则
        self._build_ninja_compile_rules_byParty()

        # 5. 链接规则
        self._build_ninja_link_rules()

        # 6. 编译目标
        # self._build_ninja_compile_objs()

        # 6.1 party 编译目标
        self._build_ninja_compile_objs_byParty()

        # 7. 链接目标
        self._build_ninja_link_objs()

        # 8. 自定义命令
        self._build_ninja_custom_commands()

        # 9. 伪目标
        self._build_ninja_phony()

        # # 10. ALIASES
        # self._build_ninja_aliases()

        self.lines.append("\n")

        # return "\n".join(self.lines)
        pass

    def _build_ninja_content(self) -> str:
        """构建 Ninja 文件内容"""
        L: list[str] = []
        h = self.helper

        # ==================================================================
        # 1. 文件头
        # ==================================================================
        L.append("# ==========================================")
        L.append("#  Auto-generated by pymakex Ninja backend")
        L.append("# ==========================================")
        L.append("")

        L.append(f"builddir = {h.get('BUILDDIR', 'BUILD')}")
        L.append("")

        # ==================================================================
        # 2. 工具链变量
        # ==================================================================
        L.append("# ---- 工具链变量 ----")
        L.append(f"cc = {h.get('CC', 'gcc')}")
        L.append(f"cxx = {h.get('CXX', 'g++')}")
        L.append(f"as = {h.get('AS', 'as')}")
        L.append(f"ld = {h.get('LD', h.get('CC', 'gcc'))}")
        L.append(f"ar = {h.get('AR', 'ar')}")
        L.append("")

        # ==================================================================
        # 3. 编译/链接标志变量
        # ==================================================================
        L.append("# ---- 编译标志 ----")

        _cflags = h.get("CFLAGS", [])
        _cxxflags = h.get("CXXFLAGS", [])
        _asflags = h.get("ASFLAGS", [])
        _ldflags = h.get("LINKFLAGS", [])
        _arflags = h.get("ARFLAGS", ["rcs"])
        _defines = h.get("DEFINES", {})
        _incpath = h.get("INCPATH", [])
        _libs = h.get("LIBS", [])
        _libpath = h.get("LIBPATH", [])

        L.append(f"cflags = {' '.join(str(f) for f in _cflags)}")
        L.append(f"cxxflags = {' '.join(str(f) for f in _cxxflags)}")
        L.append(f"asflags = {' '.join(str(f) for f in _asflags)}")
        L.append(f"ldflags = {' '.join(str(f) for f in _ldflags)}")
        L.append(f"arflags = {' '.join(str(f) for f in _arflags)}")

        _def_flags = []
        for k, v in _defines.items():
            if v == "":
                _def_flags.append(f"-D{k}")
            else:
                _def_flags.append(f"-D{k}={v}")
        L.append(f"defines = {' '.join(_def_flags)}")

        _inc_flags = [f"-I{p}" for p in _incpath]
        L.append(f"includes = {' '.join(_inc_flags)}")

        _lib_flags = [f"-l{l}" for l in _libs]
        _libpath_flags = [f"-L{p}" for p in _libpath]
        L.append(f"libs = {' '.join(_lib_flags + _libpath_flags)}")
        L.append("")

        # ==================================================================
        # 4. 编译规则 (cc / cxx / asm)  —  带 depfile 支持
        # ==================================================================
        L.append("# ---- 编译规则 ----")

        L.append("rule cc")
        L.append("  depfile = $out.d")
        L.append("  command = $cc $cflags $defines $includes -c $in -o $out")
        L.append("  description = CC $out")
        L.append("")

        L.append("rule cxx")
        L.append("  depfile = $out.d")
        L.append("  command = $cxx $cxxflags $defines $includes -c $in -o $out")
        L.append("  description = CXX $out")
        L.append("")

        L.append("rule asm")
        L.append("  command = $as $asflags $includes -c $in -o $out")
        L.append("  description = AS $out")
        L.append("")

        # ==================================================================
        # 5. 链接规则
        # ==================================================================
        L.append("# ---- 链接规则 ----")
        L.append("rule link")
        L.append("  command = $ld $ldflags -o $out $in $libs")
        L.append("  description = LINK $out")
        L.append("")

        L.append("rule ar")
        L.append("  command = $ar $arflags $out $in")
        L.append("  description = AR $out")
        L.append("")

        # ==================================================================
        # 6. 编译目标 — 逐个源文件生成 build 语句
        # ==================================================================
        L.append("# ---- 编译目标 ----")
        _all_objs: list[str] = []
        _cxx_exts = {".cpp", ".cc", ".cxx", ".c++", ".C"}
        _asm_exts = {".s", ".asm", ".S"}

        for _cmd in self._compile_commands:
            if isinstance(_cmd, dict):
                _obj = _cmd.get("obj", [""])[0] if _cmd.get("obj") else ""
                _src = _cmd.get("src", [""])[0] if _cmd.get("src") else ""
            elif isinstance(_cmd, list | tuple) and len(_cmd) >= 3:
                _obj = str(_cmd[1])
                _src = str(_cmd[2])
            else:
                continue

            if not _obj or not _src:
                continue
            _all_objs.append(_obj)

            _src_lower = _src.lower()
            if any(_src_lower.endswith(ext) for ext in _asm_exts):
                _rule = "asm"
            elif any(_src_lower.endswith(ext) for ext in _cxx_exts):
                _rule = "cxx"
            else:
                _rule = "cc"

            L.append(f"build {_obj}: {_rule} {_src}")
        L.append("")

        # ==================================================================
        # 7. 链接目标
        # ==================================================================
        if self.targets_commands:
            L.append("# ---- 链接目标 ----")
            _tgt = self.targets_commands
            _target = _tgt.get("target", [""])[0]
            _objs = _tgt.get("obj", [])
            _tgt_libs = _tgt.get("libs", [])
            _tgt_libpathes = _tgt.get("libpathes", [])
            _tgt_toolflags = _tgt.get("toolflags", [])

            _objs_str = " ".join(str(o) for o in _objs)
            _extra_libs = " ".join(str(l) for l in _tgt_libs + _tgt_libpathes)

            L.append(f"build {_target}: link {_objs_str}")
            if _extra_libs:
                L.append(f"  libs = $libs {_extra_libs}")
            if _tgt_toolflags:
                L.append(f"  ldflags = $ldflags {' '.join(str(f) for f in _tgt_toolflags)}")
            L.append("")

            L.append("# ---- 默认目标 ----")
            L.append(f"default {_target}")
            L.append("")

        # ==================================================================
        # 8. 自定义命令 (COMMANDS)
        # ==================================================================
        _commands = h.get("COMMANDS", {})
        if _commands:
            L.append("# ---- 自定义命令 ----")
            for _name, _cmd_lines in _commands.items():
                _rule_name = f"cmd_{_name}"
                L.append(f"rule {_rule_name}")
                if isinstance(_cmd_lines, list):
                    L.append(f"  command = {' && '.join(str(c) for c in _cmd_lines)}")
                else:
                    L.append(f"  command = {_cmd_lines}")
                L.append(f"  description = CMD {_name}")
                L.append("")
                L.append(f"build {_name}: {_rule_name}")
                L.append("")

        # ==================================================================
        # 9. 伪目标 (PHONIES)
        # ==================================================================
        _phonies = h.get("PHONIES", {})
        if _phonies:
            L.append("# ---- 伪目标 ----")
            for _pname, _pdeps in _phonies.items():
                _deps_str = (
                    " ".join(str(d) for d in _pdeps) if isinstance(_pdeps, list) else str(_pdeps)
                )
                L.append(f"build {_pname}: phony {_deps_str}")
            L.append("")

        # ==================================================================
        # 10. 别名 (ALIASES)
        # ==================================================================
        _aliases = h.get("ALIASES", {})
        if _aliases:
            L.append("# ---- 别名目标 ----")
            for _aname, _adeps in _aliases.items():
                _deps_str = (
                    " ".join(str(d) for d in _adeps) if isinstance(_adeps, list) else str(_adeps)
                )
                L.append(f"build {_aname}: phony {_deps_str}")
            L.append("")

        return "\n".join(L)


